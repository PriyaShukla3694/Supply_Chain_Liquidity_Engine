from __future__ import annotations

from typing import List

from pydantic import BaseModel, Field, validator


class AnswerRequest(BaseModel):
    """Payload for a grounded RAG answer request.

    * ``query`` – the user question.
    * ``limit`` – number of chunks to retrieve (1‑10). Mirrors the retrieval limits.
    """

    query: str = Field(..., description="User question for the LLM")
    limit: int = Field(5, ge=1, le=10, description="Maximum number of document chunks to retrieve")

    @validator("query")
    def non_empty_query(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Query must be a non‑empty string")
        return v.strip()


class Citation(BaseModel):
    """Reference to a retrieved chunk that the LLM cited.

    The ``index`` corresponds to the ``[index]`` marker that appears in the answer.
    """

    index: int = Field(..., ge=1, description="Citation marker number (1‑based)")
    document_name: str = Field(..., description="Source document name")
    document_type: str = Field(..., description="Source document type")
    version: str = Field(..., description="Document version string")
    chunk_index: int = Field(..., description="Zero‑based chunk index within the document")

    @validator("index")
    def positive_index(cls, v: int) -> int:
        if v < 1:
            raise ValueError("Citation index must be >= 1")
        return v


class AnswerResponse(BaseModel):
    """Response containing the LLM answer and structured citations.

    ``answer`` – the generated natural‑language answer.
    ``citations`` – list of ``Citation`` objects that map the markers used in the answer to the actual
    retrieved chunk metadata.
    ``source_chunks`` – optional echo of the retrieved chunks (useful for debugging/UI).
    """

    answer: str = Field(..., description="Grounded answer generated by the LLM")
    citations: List[Citation] = Field(..., description="Structured citation information used in the answer")
    source_chunks: List[dict] = Field(..., description="Original chunk data returned by the retrieval service")
